// English until the page says otherwise; only Spanish is translated.
let activeLanguage = 'en';

export function setLanguage(language) {
  activeLanguage = String(language || '').toLowerCase().startsWith('es') ? 'es' : 'en';
}

/** Whole strings only: a partial match would mix languages ("no capturas"). */
export function t(key, language = activeLanguage) {
  const source = String(key);
  if (!String(language).toLowerCase().startsWith('es')) return source;
  return Object.hasOwn(spanish, source) ? spanish[source] : source;
}
